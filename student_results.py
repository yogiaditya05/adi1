import requests
from rich.console import Console # type: ignore
from rich.table import Table # type: ignore
from rich.panel import Panel # type: ignore
from rich import print as rprint # type: ignore

def fetch_results():
    # Postman Mock API URL
    url = "https://485ab272-b860-4c62-80f4-fa6a80a8c9d1.mock.pstmn.io/students"
    
    console = Console()
    
    with console.status("[bold green]Fetching student results...", spinner="dots"):
        try:
            response = requests.get(url)
            response.raise_for_status()
            data = response.json()
        except Exception as e:
            console.print(f"[bold red]Error:[/bold red] Could not fetch data. {e}")
            return

    # Create a stylized table
    table = Table(title="Student Performance Portal", title_style="bold magenta", border_style="cyan")

    table.add_column("ID", justify="center", style="dim")
    table.add_column("Roll Number", style="yellow")
    table.add_column("Name", style="bold white")
    table.add_column("Marks", justify="right", style="green")
    table.add_column("City", style="blue")
    table.add_column("Status", justify="center")

    for student in data:
        marks = student.get("marks", 0)
        status = "PASS" if marks >= 40 else "FAIL"
        status_style = "bold green" if marks >= 40 else "bold red"
        
        # Highlight Aditya Yogi
        row_style = "on blue" if student.get("roll_number") == "0827rl231005" else ""
        
        table.add_row(
            str(student.get("id")),
            student.get("roll_number", "N/A"),
            student.get("name"),
            f"{marks}%",
            student.get("city"),
            status,
            style=row_style
        )

    # Display the results
    console.print("\n")
    console.print(Panel.fit(
        "[bold cyan]Student Results Live Data[/bold cyan]\n"
        "[dim]Connected to Postman Mock API[/dim]",
        border_style="bright_blue"
    ))
    console.print(table)
    console.print(f"\n[bold green]Total Students Processed:[/bold green] {len(data)}")
    console.print("[italic dim]Generated by Anti-Gravity System[/italic dim]\n")

if __name__ == "__main__":
    fetch_results()
